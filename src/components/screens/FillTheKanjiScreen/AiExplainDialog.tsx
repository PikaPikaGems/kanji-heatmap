import { Loader2, RotateCcw } from "lucide-react";
import { Dialog } from "@/components/ui/dialog";
import { ScrollableDialogContent } from "@/components/ui/scrollable-dialog-content";
import { Button } from "@/components/ui/button";
import { CopyButton } from "@/components/common/CopyButton";
import type { AiExplainState } from "@/hooks/use-ai-explain";
import { AiExplanationMarkdown } from "./AiExplanationMarkdown";

const ExplanationBody = ({ state }: { state: AiExplainState }) => {
  if (state.status === "error") {
    return <p className="text-sm text-destructive">{state.message}</p>;
  }
  if (state.status === "idle") return null;
  if (state.status === "loading" && state.text === "") {
    return (
      <p className="flex items-center gap-2 text-sm text-muted-foreground">
        <Loader2 className="w-4 h-4 animate-spin" /> Asking Grok…
      </p>
    );
  }
  return <AiExplanationMarkdown text={state.text} />;
};

export const AiExplainDialog = ({
  open,
  onClose,
  japaneseText,
  state,
  onRegenerate,
}: {
  open: boolean;
  onClose: () => void;
  japaneseText: string;
  state: AiExplainState;
  onRegenerate: () => void;
}) => (
  <Dialog open={open} onOpenChange={(next) => !next && onClose()}>
    <ScrollableDialogContent
      size="md"
      title="AI Explain"
      description="An AI explanation of the sentence's vocabulary, translation and grammar"
      titleClassName="text-left"
    >
      {/* Same clickable kanji and kana as in the reply. */}
      <div className="pb-3 mb-3 text-left border-b border-dotted">
        <AiExplanationMarkdown
          text={japaneseText}
          className="text-2xl leading-10"
        />
      </div>
      <div className="text-left">
        <ExplanationBody state={state} />
      </div>
      <div className="flex items-center justify-between gap-2 pt-3 mt-4 border-t border-dotted">
        <p className="text-xs text-muted-foreground">
          AI-generated by Grok. It can be wrong.
        </p>
        <div className="flex items-center gap-1 shrink-0">
          {state.status === "success" && (
            <CopyButton textToCopy={state.text} iconType="clipboard" />
          )}
          <Button
            type="button"
            variant="ghost"
            size="sm"
            onClick={onRegenerate}
            disabled={state.status === "loading"}
          >
            <RotateCcw /> Regenerate
          </Button>
        </div>
      </div>
    </ScrollableDialogContent>
  </Dialog>
);
