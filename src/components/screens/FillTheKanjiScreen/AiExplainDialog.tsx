import { useId, useState } from "react";
import { Loader2 } from "lucide-react";
import { Dialog } from "@/components/ui/dialog";
import { ScrollableDialogContent } from "@/components/ui/scrollable-dialog-content";
import { CopyButton } from "@/components/common/CopyButton";
import {
  DownloadMarkdownButton,
  RegenerateButton,
} from "@/components/common/AiActionButtons";
import { ResponsiveTextarea } from "@/components/common/ResponsiveTextarea";
import { DeleteWithConfirm } from "@/components/common/DeleteWithConfirm";
import { AiContentNotice } from "@/components/common/AiContentNotice";
import type { AiExplainState } from "@/hooks/use-ai-explain";
import { AiExplanationMarkdown } from "./AiExplanationMarkdown";
import { SpeakButtons } from "./SpeakButtons";
import type { SentenceSpeech } from "./use-fill-the-kanji-game";

const ExplanationBody = ({ state }: { state: AiExplainState }) => {
  if (state.status === "idle") return null;
  if (state.status === "error") {
    return (
      <>
        <p role="alert" className="mb-3 text-sm text-destructive">
          {state.message}
        </p>
        {state.text && <AiExplanationMarkdown text={state.text} />}
      </>
    );
  }
  if (state.status === "loading") {
    return (
      <>
        {state.previousText && (
          <AiExplanationMarkdown text={state.previousText} />
        )}
        <p
          role="status"
          className="flex items-center gap-2 my-3 text-sm text-muted-foreground"
        >
          <Loader2 className="w-4 h-4 animate-spin" />
          {state.previousText
            ? "Regenerating… Previous answer stays until this finishes."
            : "Asking Grok…"}
        </p>
        {state.text && (
          <div className="pt-3 border-t border-dotted">
            <p className="mb-2 text-xs text-muted-foreground">
              Pending preview
            </p>
            <AiExplanationMarkdown text={state.text} />
          </div>
        )}
      </>
    );
  }
  return (
    <>
      {state.saveWarning && (
        <p role="alert" className="mb-3 text-sm text-destructive">
          {state.saveWarning}
        </p>
      )}
      <AiExplanationMarkdown text={state.text} />
    </>
  );
};

const RegenerationControls = ({
  loading,
  onRegenerate,
}: {
  loading: boolean;
  onRegenerate: (instructions: string) => void;
}) => {
  const [instructions, setInstructions] = useState("");
  const id = useId();
  return (
    <div className="space-y-2">
      <label htmlFor={id} className="text-sm font-semibold">
        What should change? (optional)
      </label>
      <ResponsiveTextarea
        id={id}
        title="What should change?"
        value={instructions}
        onValueChange={setInstructions}
        rows={2}
        maxLength={4000}
        placeholder="Use simpler words, explain the grammar more, or focus on casual speech."
      />
      <RegenerateButton
        onClick={() => onRegenerate(instructions)}
        busy={loading}
      />
    </div>
  );
};

export const AiExplainDialog = ({
  open,
  onClose,
  japaneseText,
  speech,
  state,
  onRegenerate,
  onDelete,
}: {
  open: boolean;
  onClose: () => void;
  japaneseText: string;
  /** The game's speech for this sentence, so shortcuts and taps share a spinner. */
  speech: SentenceSpeech;
  state: AiExplainState;
  onRegenerate: (instructions: string) => void;
  onDelete: () => Promise<void>;
}) => {
  const completedText =
    state.status === "loading"
      ? state.previousText
      : "text" in state
        ? state.text
        : undefined;
  return (
    <Dialog open={open} onOpenChange={(next) => !next && onClose()}>
      <ScrollableDialogContent
        size="md"
        title="✨ AI Explain"
        description="An AI explanation of the sentence's vocabulary, translation and grammar"
        titleClassName="text-left"
      >
        <div className="pb-3 mb-3 space-y-2 text-left border-b border-dotted">
          <AiExplanationMarkdown
            text={japaneseText}
            className="text-2xl leading-10"
          />
          <SpeakButtons speech={speech} />
        </div>
        <div className="text-left">
          <ExplanationBody state={state} />
        </div>
        <div className="pt-3 mt-4 space-y-3 text-left border-t border-dotted">
          <p className="text-xs text-muted-foreground">AI-generated by Grok.</p>
          <AiContentNotice />
          {completedText && (
            <div className="flex flex-wrap items-center gap-1">
              <CopyButton textToCopy={completedText} iconType="clipboard" />
              <DownloadMarkdownButton
                markdown={completedText}
                filename="sentence-explanation.md"
              />
              <DeleteWithConfirm
                question="Delete this saved explanation?"
                disabled={state.status === "loading"}
                onDelete={onDelete}
              />
            </div>
          )}
          {/* Nothing to regenerate while the first answer is still coming. */}
          {!(state.status === "loading" && !state.previousText) && (
            <RegenerationControls
              loading={state.status === "loading"}
              onRegenerate={onRegenerate}
            />
          )}
        </div>
      </ScrollableDialogContent>
    </Dialog>
  );
};
