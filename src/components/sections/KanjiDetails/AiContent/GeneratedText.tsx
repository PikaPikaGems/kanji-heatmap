import { cn } from "@/lib/utils";
import { SectionLoading } from "@/components/common/SectionLoading";
import { useRef, useState } from "react";
import { CopyButton } from "@/components/common/CopyButton";
import {
  AiPrimaryButton,
  AiRequestFeedback,
  DownloadMarkdownButton,
  RegenerateButton,
} from "@/components/common/AiActionButtons";
import { CollapsibleSection } from "@/components/common/CollapsibleSection";
import { DeleteWithConfirm } from "@/components/common/DeleteWithConfirm";
import { SavedStorageNotice } from "@/components/common/SavedStorageNotice";
import { deleteTextResult } from "@/lib/ai-explain/storage";
import { ResponsiveTextarea } from "@/components/common/ResponsiveTextarea";
import { scrollResultIntoView } from "@/lib/scroll";
import { useAiDrawerText } from "@/hooks/use-ai-drawer-text";
import { normalizeAiMarkdown } from "@/lib/ai-explain/markdown";
import type { AiExplainSettings } from "@/lib/ai-explain/preferences";
import { HighlightKanjiSwitch } from "../KanjiStudyNotes/HighlightKanjiSwitch";
import { MarkdownPreview } from "../KanjiStudyNotes/MarkdownPreview";
import { AiContentNotice } from "@/components/common/AiContentNotice";
import { AiAudio } from "./AiAudio";

export const GeneratedText = ({
  id,
  filename,
  generateLabel,
  makePrompt,
}: {
  id: string;
  filename: string;
  generateLabel: string;
  makePrompt: (settings: AiExplainSettings) => string;
}) => {
  const { state, generate, cancel } = useAiDrawerText(id, makePrompt);
  const [instructions, setInstructions] = useState("");
  const [changesOpen, setChangesOpen] = useState(false);
  const topRef = useRef<HTMLDivElement>(null);
  const busy = state.status === "generating";
  const runGenerate = async () => {
    if (!(await generate(instructions))) return;
    setChangesOpen(false);
    // The result sits at the top, so its position is known before it renders.
    scrollResultIntoView(topRef.current);
  };
  const result = state.result;
  const markdown = result ? normalizeAiMarkdown(result.markdown) : "";

  if (state.status === "loading") return <SectionLoading />;

  return (
    <div ref={topRef} className="space-y-4 text-left">
      {result && (
        <>
          <HighlightKanjiSwitch className="pl-2" />
          <p className="pl-2 text-xs text-muted-foreground">
            AI-generated by Grok
          </p>
          <div className="rounded-xl border border-foreground/20 py-4">
            <MarkdownPreview source={markdown} />
          </div>
          {result.sources.length > 0 && (
            <details className="text-xs">
              <summary className="cursor-pointer">Sources</summary>
              <ul className="mt-2 space-y-2">
                {result.sources
                  .filter((source) => /^https?:\/\//i.test(source.url))
                  .map((source) => (
                    <li key={source.url}>
                      <a
                        className="break-words underline"
                        href={source.url}
                        target="_blank"
                        rel="noopener noreferrer"
                      >
                        {source.title || source.url}
                      </a>
                    </li>
                  ))}
              </ul>
            </details>
          )}
          <div className="flex flex-wrap items-center gap-2">
            <CopyButton textToCopy={markdown} iconType="clipboard" />
            <DownloadMarkdownButton
              markdown={markdown}
              filename={`${filename}.md`}
            />
            <DeleteWithConfirm
              question="Delete this AI answer and its MP3? Download it first if you want to keep it."
              disabled={busy}
              onDelete={() => deleteTextResult(id)}
            />
          </div>
          <AiAudio
            key={result.fingerprint}
            sourceId={id}
            markdown={result.markdown}
            filename={filename}
          />
          <CollapsibleSection
            title="What should change? (optional)"
            open={changesOpen}
            onOpenChange={setChangesOpen}
          >
            <ResponsiveTextarea
              aria-label="What should change?"
              title="What should change?"
              value={instructions}
              onValueChange={setInstructions}
              placeholder="Make it shorter, add everyday examples, or explain one point more clearly."
              disabled={busy}
              rows={2}
            />
          </CollapsibleSection>
        </>
      )}
      <SavedStorageNotice kind="text" />
      {/* Regenerate sits centered under the answer; Generate stays left. */}
      <div className={cn("flex flex-wrap gap-2", result && "justify-center")}>
        {result ? (
          <RegenerateButton busy={busy} onClick={() => void runGenerate()} />
        ) : (
          <AiPrimaryButton busy={busy} onClick={() => void runGenerate()}>
            {generateLabel}
          </AiPrimaryButton>
        )}
      </div>
      <AiRequestFeedback
        busy={busy}
        onCancel={cancel}
        error={state.message}
        warning={state.warning}
      >
        {state.preview && (
          <details>
            <summary className="cursor-pointer text-xs">Pending answer</summary>
            <MarkdownPreview source={normalizeAiMarkdown(state.preview)} />
          </details>
        )}
      </AiRequestFeedback>
      <AiContentNotice />
    </div>
  );
};
