import { useState } from "react";
import { Download, Loader2, RotateCcw } from "lucide-react";
import { Button } from "@/components/ui/button";
import { PracticeButton } from "@/components/ui/practice-button";
import { CopyButton } from "@/components/common/CopyButton";
import { useAiDrawerText } from "@/hooks/use-ai-drawer-text";
import type { AiExplainSettings } from "@/lib/ai-explain/preferences";
import { HighlightKanjiSwitch } from "../KanjiStudyNotes/HighlightKanjiSwitch";
import { MarkdownPreview } from "../KanjiStudyNotes/MarkdownPreview";
import { AiContentNotice } from "./AiContentNotice";
import { AiAudio } from "./AiAudio";

export const GeneratedText = ({
  id,
  filename,
  generateLabel,
  makePrompt,
  emptyMessage,
}: {
  id: string;
  filename: string;
  generateLabel: string;
  makePrompt: (settings: AiExplainSettings) => string;
  emptyMessage?: string;
}) => {
  const { state, generate, cancel } = useAiDrawerText(id, makePrompt);
  const [instructions, setInstructions] = useState("");
  const [downloadError, setDownloadError] = useState("");
  const busy = state.status === "generating";
  const result = state.result;

  const download = async () => {
    try {
      const { downloadBlob } = await import("@/lib/ai-explain/download");
      downloadBlob(
        new Blob([result?.markdown ?? ""], {
          type: "text/markdown;charset=utf-8",
        }),
        `${filename}.md`
      );
      setDownloadError("");
    } catch {
      setDownloadError("Couldn't download the Markdown. Please try again.");
    }
  };

  if (state.status === "loading") {
    return (
      <p className="flex items-center gap-2 p-3 text-sm text-muted-foreground">
        <Loader2 className="size-4 animate-spin" /> Loading saved AI content…
      </p>
    );
  }

  return (
    <div className="space-y-4 text-left">
      {!result && emptyMessage && (
        <p className="p-4 text-center text-sm text-muted-foreground">
          {emptyMessage}
        </p>
      )}
      {result && (
        <>
          <div className="flex flex-wrap items-center justify-between gap-2">
            <span className="text-xs text-muted-foreground">
              AI-generated by Grok
            </span>
            <HighlightKanjiSwitch />
          </div>
          <div className="rounded-xl border border-foreground/20 py-4">
            <MarkdownPreview source={result.markdown} />
          </div>
          {result.sources.length > 0 && (
            <details className="text-xs">
              <summary className="cursor-pointer">Sources</summary>
              <ul className="mt-2 space-y-2">
                {result.sources
                  .filter((source) => /^https?:\/\//i.test(source.url))
                  .map((source) => (
                    <li key={source.url}>
                      <a
                        className="break-words underline"
                        href={source.url}
                        target="_blank"
                        rel="noopener noreferrer"
                      >
                        {source.title || source.url}
                      </a>
                    </li>
                  ))}
              </ul>
            </details>
          )}
          <div className="flex flex-wrap items-center gap-2">
            <CopyButton textToCopy={result.markdown} iconType="clipboard" />
            <Button variant="outline" size="sm" onClick={() => void download()}>
              <Download /> Download Markdown
            </Button>
          </div>
          <AiAudio
            key={result.fingerprint}
            sourceId={id}
            markdown={result.markdown}
            filename={filename}
          />
          <label className="block space-y-2 text-sm">
            <span>What should change? (optional)</span>
            <textarea
              className="w-full rounded-md border border-input bg-background px-3 py-2 text-sm focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
              value={instructions}
              onChange={(event) => setInstructions(event.target.value)}
              placeholder="Make it shorter, add everyday examples, or explain one point more clearly."
              disabled={busy}
              rows={2}
            />
          </label>
        </>
      )}
      {busy && (
        <div role="status" className="space-y-2">
          <p className="flex items-center gap-2 text-sm">
            <Loader2 className="size-4 animate-spin" /> Asking Grok and
            searching the web…
          </p>
          {state.preview && (
            <details>
              <summary className="cursor-pointer text-xs">
                Pending answer
              </summary>
              <MarkdownPreview source={state.preview} />
            </details>
          )}
        </div>
      )}
      {(state.message || downloadError) && (
        <p role="alert" className="text-sm text-destructive">
          {state.message || downloadError}
        </p>
      )}
      {state.warning && (
        <p role="status" className="text-sm text-amber-700 dark:text-amber-400">
          {state.warning}
        </p>
      )}
      <div className="flex flex-wrap gap-2">
        {result ? (
          <Button
            variant="outline"
            size="sm"
            disabled={busy}
            onClick={() => void generate(instructions)}
          >
            <RotateCcw /> Regenerate
          </Button>
        ) : (
          <PracticeButton
            variant="primary"
            size="md"
            className="h-auto min-h-12 whitespace-normal px-3 py-3 text-sm sm:text-base"
            disabled={busy}
            onClick={() => void generate(instructions)}
          >
            {generateLabel}
          </PracticeButton>
        )}
        {busy && (
          <Button variant="ghost" size="sm" onClick={cancel}>
            Cancel
          </Button>
        )}
      </div>
      <AiContentNotice />
    </div>
  );
};
